const isDigit = (code) => code >= 48 && code <= 57;

/**
 * Natural order: photo-2 before photo-10, case-insensitive, and the same on
 * every machine (no locale tables involved). A total order: two different
 * strings never compare equal.
 */
export function naturalCompare(a, b) {
  const ax = String(a).match(/\d+|\D+/g) ?? [];
  const bx = String(b).match(/\d+|\D+/g) ?? [];
  const n = Math.min(ax.length, bx.length);
  for (let i = 0; i < n; i += 1) {
    const x = ax[i];
    const y = bx[i];
    const xd = isDigit(x.charCodeAt(0));
    const yd = isDigit(y.charCodeAt(0));
    if (xd && yd) {
      const xs = x.replace(/^0+(?=\d)/, "");
      const ys = y.replace(/^0+(?=\d)/, "");
      if (xs.length !== ys.length) return xs.length - ys.length;
      if (xs !== ys) return xs < ys ? -1 : 1;
    } else if (xd !== yd) {
      return xd ? -1 : 1;
    } else {
      const xl = x.toLowerCase();
      const yl = y.toLowerCase();
      if (xl !== yl) return xl < yl ? -1 : 1;
    }
  }
  if (ax.length !== bx.length) return ax.length - bx.length;
  return a < b ? -1 : a > b ? 1 : 0;
}

const stem = (file) => file.replace(/\.[^.]*$/, "");

/** File-name order: the name without its ending decides, so "a.jpg" sorts before "a-2.jpg". */
export function compareFileNames(a, b) {
  return naturalCompare(stem(a), stem(b)) || naturalCompare(a, b);
}

/** Folder order: natural order level by level, a folder before the folders inside it. */
export function compareFolders(a, b) {
  const as = a === "" ? [] : a.split("/");
  const bs = b === "" ? [] : b.split("/");
  const n = Math.min(as.length, bs.length);
  for (let i = 0; i < n; i += 1) {
    const c = naturalCompare(as[i], bs[i]);
    if (c) return c;
  }
  return as.length - bs.length;
}

/** Path order: folder by folder, then file-name order inside a folder. */
export function comparePaths(a, b) {
  const cut = (p) => {
    const at = p.lastIndexOf("/");
    return at < 0 ? ["", p] : [p.slice(0, at), p.slice(at + 1)];
  };
  const [da, fa] = cut(a);
  const [db, fb] = cut(b);
  return compareFolders(da, db) || compareFileNames(fa, fb);
}

const byCodePoint = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * Fallback alt text for a photo nobody has described yet: the file name
 * without a leading number, dashes and underscores as spaces. Mirrored by
 * altFromFileName() in src/lib/media.ts (a test keeps the two in step).
 */
export function deriveAlt(file) {
  const words = stem(file)
    .replace(/^\d+(?:[-_ .]+|$)/, "")
    .replace(/[-_]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  return words || "Photo";
}

// The two rules of scripts/check-content-claims.mjs, copied so photo text is
// held to the same standard as the page copy without editing that script.
const CLAIM_DOLLAR = /\$\d[\d,]*/g;
const CLAIM_MINUTES = /(?<![.\w-])\d{1,2}(?:\s*[–-]\s*\d{1,2})?\s*(?:min\b(?!-)|minutes?\b)/g;
const CLAIM_RESPONSE_WORDS = /respon|arriv|dispatch|on our way|on-site|onsite|show up/i;

/** Price or response-time figures in a piece of photo text. Empty when it is clean. */
export function findClaims(text) {
  const hits = [];
  for (const line of String(text).split("\n")) {
    for (const m of line.matchAll(CLAIM_DOLLAR)) hits.push({ kind: "price", text: m[0] });
    if (CLAIM_RESPONSE_WORDS.test(line)) {
      for (const m of line.matchAll(CLAIM_MINUTES)) hits.push({ kind: "response time", text: m[0] });
    }
  }
  return hits;
}

/**
 * Where a JSON file goes wrong, in words an owner can act on. Returns null
 * for valid JSON. JSON.parse stays the judge of validity; this only finds
 * the place, because the engine's own message often has no position.
 */
export function locateJsonError(text) {
  let i = 0;
  const n = text.length;
  class Stop extends Error {}
  let found = null;
  const fail = (message, at = i) => {
    found = { offset: at, message };
    throw new Stop();
  };
  const ws = () => {
    while (i < n && (text[i] === " " || text[i] === "\t" || text[i] === "\n" || text[i] === "\r")) i += 1;
  };
  const CURLY = new Set(["“", "”", "‘", "’"]);
  const string = () => {
    i += 1;
    while (i < n) {
      const c = text[i];
      if (c === '"') {
        i += 1;
        return;
      }
      if (c === "\n" || c === "\r") fail('a closing quote (") is missing on this line');
      if (c === "\\") {
        const e = text[i + 1];
        if (e === "u") {
          if (!/^[0-9a-fA-F]{4}$/.test(text.slice(i + 2, i + 6))) fail("a \\u must be followed by four hex digits");
          i += 6;
          continue;
        }
        if (!'"\\/bfnrt'.includes(e ?? "\0")) fail("a backslash (\\) must be written twice (\\\\)");
        i += 2;
        continue;
      }
      if (c < " ") fail("a tab or control character is inside the quotes");
      i += 1;
    }
    fail('a closing quote (") is missing', n);
  };
  const number = () => {
    const m = /^-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d+)?/.exec(text.slice(i, i + 64));
    if (!m) fail("this is not a number");
    i += m[0].length;
  };
  const unexpected = (what) => {
    if (i >= n) fail(`the file ends early (${what} is missing)`, n);
    const c = text[i];
    if (c === "'") fail("use double quotes (\") instead of single quotes (')");
    if (CURLY.has(c)) fail('curly quotes were typed here; replace them with plain straight quotes (")');
    if (text.startsWith("//", i) || text.startsWith("/*", i)) fail('notes starting with // are not allowed in this kind of file; use a "_note" entry instead');
    fail(`${what} is expected here, found ${JSON.stringify(c)}`);
  };
  const value = () => {
    ws();
    if (i >= n) unexpected("a value");
    const c = text[i];
    if (c === "{") return object();
    if (c === "[") return array();
    if (c === '"') return string();
    if (c === "-" || isDigit(c.charCodeAt(0))) return number();
    for (const word of ["true", "false", "null"]) {
      if (text.startsWith(word, i)) {
        i += word.length;
        return undefined;
      }
    }
    if (c === "}" || c === "]" || c === ",") fail(`a value is missing before ${JSON.stringify(c)}`);
    return unexpected("a value");
  };
  const object = () => {
    i += 1;
    ws();
    if (text[i] === "}") {
      i += 1;
      return;
    }
    for (;;) {
      ws();
      if (text[i] === "}") fail("remove the comma before this }");
      if (text[i] !== '"') unexpected('a name in double quotes (")');
      string();
      ws();
      if (text[i] !== ":") unexpected("a colon (:)");
      i += 1;
      value();
      ws();
      if (text[i] === ",") {
        i += 1;
        continue;
      }
      if (text[i] === "}") {
        i += 1;
        return;
      }
      if (text[i] === '"') fail("a comma (,) is missing at the end of the line before this one");
      unexpected("a comma (,) or a closing }");
    }
  };
  const array = () => {
    i += 1;
    ws();
    if (text[i] === "]") {
      i += 1;
      return;
    }
    for (;;) {
      ws();
      if (text[i] === "]") fail("remove the comma before this ]");
      value();
      ws();
      if (text[i] === ",") {
        i += 1;
        continue;
      }
      if (text[i] === "]") {
        i += 1;
        return;
      }
      unexpected("a comma (,) or a closing ]");
    }
  };
  try {
    value();
    ws();
    if (i < n) fail("there is extra text after the end of the settings");
  } catch (err) {
    if (!(err instanceof Stop)) throw err;
  }
  if (!found) return null;
  const before = text.slice(0, found.offset);
  const line = before.split("\n").length;
  const column = found.offset - (before.lastIndexOf("\n") + 1) + 1;
  return { offset: found.offset, line, column, message: found.message };
}

/** Parse owner-edited JSON. Never throws: returns { ok, data } or { ok: false, where }. */
export function parseOwnerJson(raw) {
  const text = raw.charCodeAt(0) === 0xfeff ? raw.slice(1) : raw;
  try {
    return { ok: true, data: JSON.parse(text) };
  } catch (err) {
    const at = locateJsonError(text);
    const where = at ? `line ${at.line}, column ${at.column}: ${at.message}` : String(err.message);
    return { ok: false, where };
  }
}

/** "4/5", "4:5", "0.8" or 0.8 -> width divided by height. NaN when it is not a usable shape. */
export function parseAspect(value) {
  if (typeof value === "number") return value > 0 && Number.isFinite(value) ? value : NaN;
  const m = /^\s*(\d+(?:\.\d+)?)\s*(?:[/:x]\s*(\d+(?:\.\d+)?))?\s*$/.exec(String(value ?? ""));
  if (!m) return NaN;
  const w = Number(m[1]);
  const h = m[2] === undefined ? 1 : Number(m[2]);
  return w > 0 && h > 0 ? w / h : NaN;
}

const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v));

/**
 * The largest box of the wanted shape that fits inside the picture, centred
 * on the focal point (0..1 from the left, 0..1 from the top) and pushed back
 * inside the picture when the focal point is near an edge. Pure maths: the
 * phone cut of a slot is this box and nothing else.
 */
export function mobileCropBox({ width, height, aspect, focal = [0.5, 0.5] }) {
  let w;
  let h;
  if (width / height > aspect) {
    h = height;
    w = Math.round(height * aspect);
  } else {
    w = width;
    h = Math.round(width / aspect);
  }
  w = clamp(w, 1, width);
  h = clamp(h, 1, height);
  const fx = clamp(Number(focal[0]), 0, 1);
  const fy = clamp(Number(focal[1]), 0, 1);
  return {
    left: clamp(Math.round(fx * width - w / 2), 0, width - w),
    top: clamp(Math.round(fy * height - h / 2), 0, height - h),
    width: w,
    height: h,
  };
}

/** Does the EXIF block carry GPS coordinates (latitude or longitude)? */
export function exifHasGps(buf) {
  try {
    let o = 0;
    if (buf.length > 6 && buf.toString("latin1", 0, 4) === "Exif") o = 6;
    const order = buf.toString("latin1", o, o + 2);
    if (order !== "II" && order !== "MM") return false;
    const le = order === "II";
    const u16 = (p) => (le ? buf.readUInt16LE(p) : buf.readUInt16BE(p));
    const u32 = (p) => (le ? buf.readUInt32LE(p) : buf.readUInt32BE(p));
    if (u16(o + 2) !== 42) return false;
    const ifd0 = o + u32(o + 4);
    const count = u16(ifd0);
    for (let k = 0; k < count; k += 1) {
      const entry = ifd0 + 2 + k * 12;
      if (u16(entry) !== 0x8825) continue;
      const gps = o + u32(entry + 8);
      const tags = u16(gps);
      for (let j = 0; j < tags; j += 1) {
        const tag = u16(gps + 2 + j * 12);
        if (tag === 2 || tag === 4) return true;
      }
      return false;
    }
    return false;
  } catch {
    return false;
  }
}

const hex2 = (v) => Math.round(v).toString(16).padStart(2, "0");

/**
 * Dominant colour of a small RGBA thumbnail: the fullest cell of a 16x16x16
 * colour grid, reported as the average of the pixels that fell into it.
 * See-through pixels are left out. Also reports whether anything is see-through.
 */
export function dominantColour(data, channels) {
  const counts = new Uint32Array(4096);
  const sums = new Float64Array(4096 * 3);
  let alpha = false;
  for (let p = 0; p + channels <= data.length; p += channels) {
    const r = data[p];
    const g = channels >= 3 ? data[p + 1] : r;
    const b = channels >= 3 ? data[p + 2] : r;
    const a = channels === 4 ? data[p + 3] : channels === 2 ? data[p + 1] : 255;
    if (a < 250) alpha = true;
    if (a < 128) continue;
    const bin = ((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4);
    counts[bin] += 1;
    sums[bin * 3] += r;
    sums[bin * 3 + 1] += g;
    sums[bin * 3 + 2] += b;
  }
  let best = -1;
  for (let bin = 0; bin < 4096; bin += 1) {
    if (counts[bin] > 0 && (best < 0 || counts[bin] > counts[best])) best = bin;
  }
  if (best < 0) return { color: "#ffffff", alpha: true };
  const c = counts[best];
  return { color: `#${hex2(sums[best * 3] / c)}${hex2(sums[best * 3 + 1] / c)}${hex2(sums[best * 3 + 2] / c)}`, alpha };
}

const SAFE_SEGMENT = /^[A-Za-z0-9._-]+$/;
const CANONICAL_EXT = { jpeg: ["jpg", "jpeg"], png: ["png"], webp: ["webp"], avif: ["avif"], gif: ["gif"] };

/**
 * A picture is imported straight from public/images only when that is known
 * to work everywhere: every part of its path is plain letters, digits, dot,
 * dash or underscore, and its ending is lower-case and matches what the file
 * really is. Measured on Next 16.4 (Turbopack): an upper-case ending
 * ("IMG_1.JPG") is refused by the build, and a name that mixes a space with
 * "&", "," or "(" ("C&S Logo.png") builds but answers 404 from `next start`.
 * Anything else gets a byte-for-byte copy under a safe name in
 * src/generated/staged and that copy is imported instead. The original is
 * left exactly as it is.
 */
export function needsStaging(rel, format) {
  const segments = rel.split("/");
  if (!segments.every((s) => SAFE_SEGMENT.test(s))) return true;
  const ext = path.extname(rel).slice(1);
  return !(CANONICAL_EXT[format] ?? []).includes(ext);
}

/** Safe file name for a staged copy: readable, and tagged with a hash of the public path so it is unique. */
export function stagedName(rel, format, tagLength = 6) {
  const base = stem(path.posix.basename(rel))
    .replace(/[^A-Za-z0-9._-]+/g, "-")
    .replace(/^[-.]+|[-.]+$/g, "");
  const tag = createHash("sha256").update(rel).digest("hex").slice(0, tagLength);
  return `${base || "image"}-${tag}.${CANONICAL_EXT[format]?.[0] ?? "jpg"}`;
}

