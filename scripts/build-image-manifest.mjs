async function loadCache(cacheDir, tool) {
  const raw = await readIfExists(path.join(cacheDir, "measurements.json"), "utf8");
  if (raw) {
    try {
      const data = JSON.parse(raw);
      if (data.v === CACHE_VERSION && data.tool === tool && data.files && data.derived) return data;
    } catch {
      /* a broken cache is simply rebuilt */
    }
  }
  return { v: CACHE_VERSION, tool, files: {}, derived: {} };
}

async function saveCache(cacheDir, cache) {
  try {
    await writeIfChanged(path.join(cacheDir, "measurements.json"), JSON.stringify(cache));
  } catch {
    /* the cache is an accelerator, never a requirement */
  }
}

async function sha256File(abs) {
  return createHash("sha256").update(await readFile(abs)).digest("hex");
}

/** Open one picture and read everything the manifest needs from it. */
async function measure(sharp, item) {
  try {
    const meta = await sharp(item.abs, { failOn: "none" }).metadata();
    if (item.kind === "vector") {
      return { w: meta.width ?? 0, h: meta.height ?? 0, f: "svg" };
    }
    let format = meta.format;
    if (format === "heif") format = meta.compression === "av1" ? "avif" : "heic";
    if (!CANONICAL_EXT[format]) {
      return { bad: format === "heic" ? "heic" : format === "tiff" ? "tiff" : "unreadable", f: format };
    }
    const turned = (meta.orientation ?? 1) >= 5;
    const w = turned ? meta.height : meta.width;
    const h = turned ? meta.width : meta.height;
    if (!w || !h) return { bad: "unreadable" };
    const { data, info } = await sharp(item.abs, { failOn: "none" })
      .rotate()
      .resize(48, 48, { fit: "inside" })
      .toColourspace("srgb")
      .raw()
      .toBuffer({ resolveWithObject: true });
    const { color, alpha } = dominantColour(data, info.channels);
    const xmp = meta.xmp ? meta.xmp.toString("latin1") : "";
    const gps = (meta.exif ? exifHasGps(meta.exif) : false) || /GPSLatitude|GPSLongitude/.test(xmp);
    const out = { w, h, f: format, c: color };
    if (alpha) out.a = true;
    if (meta.exif) out.x = true;
    if (gps) out.g = true;
    return out;
  } catch {
    return { bad: "unreadable" };
  }
}

/**
 * Size, colour and fingerprint of every file, from the cache when the file
 * has the same path, size and modified time as last run. A moved or renamed
 * file is recognised by its fingerprint and is not opened again.
 */
async function measureAll(items, cache, counters) {
  const bySha = new Map();
  for (const entry of Object.values(cache.files)) bySha.set(`${entry.sha}|${entry.s}`, entry);
  const fresh = {};
  await pool(items, 12, async (item) => {
    let info;
    try {
      info = await stat(item.abs);
    } catch {
      return;
    }
    const prev = cache.files[item.key];
    if (prev && prev.s === info.size && prev.t === info.mtimeMs) {
      fresh[item.key] = prev;
      counters.cached += 1;
      return;
    }
    const sha = await sha256File(item.abs);
    const same = bySha.get(`${sha}|${info.size}`);
    let m;
    if (same) {
      m = same.m;
      counters.cached += 1;
    } else {
      m = await measure(await loadSharp(), item);
      counters.measured += 1;
    }
    fresh[item.key] = { s: info.size, t: info.mtimeMs, sha, m };
  });
  return fresh;
}

