/**
 * Everything under public/images, sorted. Dot files are ignored; holding
 * folders (_incoming) are listed separately under `held` so the privacy check
 * can still look at them while the site never shows them.
 */
export async function scanImages(imagesDir) {
  const files = [];
  const held = [];
  const dirs = [];
  const metaFiles = new Map();
  const unsupported = [];

  async function walk(dir, relDir, holding) {
    let entries;
    try {
      entries = await readdir(dir, { withFileTypes: true });
    } catch {
      return;
    }
    entries.sort((a, b) => byCodePoint(a.name, b.name));
    if (!holding) dirs.push(relDir);
    for (const entry of entries) {
      if (entry.name.startsWith(".")) continue;
      const abs = path.join(dir, entry.name);
      const childRel = relDir ? `${relDir}/${entry.name}` : entry.name;
      let isDir = entry.isDirectory();
      let isFile = entry.isFile();
      if (entry.isSymbolicLink()) {
        try {
          const s = await stat(abs);
          isDir = s.isDirectory();
          isFile = s.isFile();
        } catch {
          continue;
        }
      }
      if (isDir) {
        await walk(abs, childRel, holding || SKIP_DIRS.has(entry.name));
      } else if (isFile) {
        const ext = path.extname(entry.name).toLowerCase();
        if (UNSUPPORTED_EXT.has(ext)) {
          unsupported.push({ rel: childRel, abs, ext });
        } else if (RASTER_EXT.has(ext) || VECTOR_EXT.has(ext)) {
          const item = { rel: childRel, folder: relDir, file: entry.name, abs, ext, kind: VECTOR_EXT.has(ext) ? "vector" : "raster" };
          (holding ? held : files).push(item);
        } else if (!holding && entry.name === "images.json") {
          metaFiles.set(relDir, abs);
        }
      }
    }
  }

  await walk(imagesDir, "", false);
  return { files, held, dirs, metaFiles, unsupported };
}

