/**
 * Image manifest.
 *
 * Turns "the files that are in public/images right now" into data the site
 * renders from, so a photo dropped into a folder (or replaced under the same
 * name) shows up without anyone editing page code:
 *
 *   src/generated/images.ts         one static import per picture. Next hashes
 *                                   the file contents into the URL
 *                                   (/_next/static/media/<name>.<hash>.<ext>),
 *                                   so a replaced file can never be served
 *                                   from an old cache.
 *   src/generated/images-meta.json  plain data: size, colour, alt text,
 *                                   captions, the ordered photo list of every
 *                                   folder, and the fixed slots from
 *                                   src/content/media.json.
 *   src/generated/derived/          crops declared in src/content/media.json
 *                                   (the phone cut of the hero, logo crops).
 *   src/generated/staged/           byte-for-byte copies of pictures whose
 *                                   file name is not safe in a URL (see
 *                                   needsStaging below).
 *
 * Everything in src/generated is git-ignored and rebuilt by this script:
 *
 *   node scripts/build-image-manifest.mjs            # write
 *   node scripts/build-image-manifest.mjs --quiet    # write, print problems only
 *   node scripts/build-image-manifest.mjs --check    # write nothing, exit 1 when stale
 *   node scripts/build-image-manifest.mjs --root <dir>   # another project root (tests)
 *
 * It runs after install, before dev, before tests and before every build
 * (see docs/forms-and-photos.md), and scripts/dev.mjs re-runs it whenever
 * public/images or src/content/media.json changes.
 *
 * Owner mistakes fail softly. An images.json with a typo prints one line and
 * that folder falls back to file-name order and derived alt text. Only a price
 * or a response-time figure typed into photo text stops the run, exactly like
 * scripts/check-content-claims.mjs does for the page copy.
 *
 * Originals are never modified: this script only reads public/images.
 */

