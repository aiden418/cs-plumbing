/** "a.jpg", "b.jpg" and 3 more */
export function nameList(names, max = 6) {
  const shown = names.slice(0, max).map((n) => `"${n}"`);
  const more = names.length - shown.length;
  if (more > 0) return `${shown.join(", ")} and ${more} more`;
  if (shown.length <= 1) return shown.join("");
  return `${shown.slice(0, -1).join(", ")} and ${shown.at(-1)}`;
}

async function pool(items, size, fn) {
  const out = new Array(items.length);
  let next = 0;
  const workers = Array.from({ length: Math.min(size, items.length) }, async () => {
    while (next < items.length) {
      const k = next;
      next += 1;
      out[k] = await fn(items[k], k);
    }
  });
  await Promise.all(workers);
  return out;
}

async function readIfExists(file, encoding) {
  try {
    return await readFile(file, encoding);
  } catch {
    return null;
  }
}

/** Write through a temp file so a dev server never reads half a file. True when the file changed. */
async function writeIfChanged(file, content) {
  const isText = typeof content === "string";
  const prev = await readIfExists(file, isText ? "utf8" : undefined);
  if (prev !== null && (isText ? prev === content : Buffer.compare(prev, content) === 0)) return false;
  await mkdir(path.dirname(file), { recursive: true });
  const tmp = `${file}.tmp-${process.pid}`;
  await writeFile(tmp, content);
  await rename(tmp, file);
  return true;
}

