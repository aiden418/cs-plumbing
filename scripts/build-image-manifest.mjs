function asFlag(value) {
  if (value === true || value === "true") return true;
  if (value === false || value === "false") return false;
  return null;
}

/**
 * One folder's images.json, normalised. Problems are collected, never thrown:
 * a wrong value loses only that one setting.
 */
function readFolderSettings(raw, jsonRel, fileNames, problems) {
  const parsed = parseOwnerJson(raw);
  if (!parsed.ok) {
    problems.push({
      level: "warn",
      code: "json-invalid",
      file: jsonRel,
      message: `${jsonRel} has a typo (${parsed.where}), so the descriptions and settings in it are ignored until it is fixed; the photos in that folder still show.`,
    });
    return { state: "invalid", entries: new Map() };
  }
  const data = parsed.data;
  if (data === null || typeof data !== "object" || Array.isArray(data)) {
    problems.push({
      level: "warn",
      code: "json-shape",
      file: jsonRel,
      message: `${jsonRel} must be one { } block with a file name for each entry, so it is ignored until that is fixed; the photos in that folder still show.`,
    });
    return { state: "invalid", entries: new Map() };
  }

  const entries = new Map();
  // Accented names can be stored in two equivalent spellings (a Mac archive
  // often uses the other one); either matches.
  const onDisk = new Map(fileNames.map((f) => [f.normalize("NFC"), f]));
  const lower = new Map(fileNames.map((f) => [f.toLowerCase(), f]));
  const missing = [];
  const nearMisses = [];
  const unknown = new Map();

  for (const [name, value] of Object.entries(data)) {
    if (name.startsWith("_")) continue; // a note the owner left for themselves
    if (value === null || typeof value !== "object" || Array.isArray(value)) {
      problems.push({
        level: "warn",
        code: "json-shape",
        file: jsonRel,
        key: name,
        message: `${jsonRel}: the entry for "${name}" must be a { } block of settings, so it is ignored.`,
      });
      continue;
    }
    const fileName = onDisk.get(name.normalize("NFC"));
    if (fileName === undefined) {
      missing.push(name);
      const near = lower.get(name.toLowerCase());
      if (near) nearMisses.push(near);
      continue;
    }
    const entry = {};
    for (const [field, v] of Object.entries(value)) {
      if (field.startsWith("_")) continue;
      const wrong = (expected) =>
        problems.push({
          level: "warn",
          code: "json-shape",
          file: jsonRel,
          key: name,
          message: `${jsonRel}: "${field}" for "${name}" must be ${expected}, so that one setting is ignored.`,
        });
      if (META_TEXT_FIELDS.includes(field)) {
        if (typeof v !== "string") wrong("text in double quotes");
        else if (v.trim()) entry[field] = v.trim();
      } else if (field === "id") {
        if (typeof v === "string" || typeof v === "number") {
          if (String(v).trim()) entry.id = String(v).trim();
        } else wrong("text or a number");
      } else if (field === "order") {
        const num = typeof v === "number" ? v : typeof v === "string" && v.trim() !== "" ? Number(v) : NaN;
        if (Number.isFinite(num)) entry.order = num;
        else wrong("a number");
      } else if (META_FLAG_FIELDS.includes(field)) {
        const flag = asFlag(v);
        if (flag === null) wrong("true or false");
        else if (flag) entry[field] = true;
      } else {
        if (!unknown.has(field)) unknown.set(field, name);
      }
    }
    for (const field of CLAIM_FIELDS) {
      if (!entry[field]) continue;
      const hits = findClaims(entry[field]);
      if (hits.length === 0) continue;
      problems.push({
        level: "error",
        code: "claims",
        file: jsonRel,
        key: `${name} > ${field}`,
        message: `${jsonRel}: "${field}" for "${name}" contains a ${hits[0].kind} ("${hits[0].text}"); prices and response times must not be typed into photo text, so remove it and run this again.`,
      });
      delete entry[field]; // never publish it, even while the run fails
    }
    entries.set(fileName, entry);
  }

  if (missing.length > 0) {
    const one = missing.length === 1;
    const hint = nearMisses.length > 0 ? ` (the folder does have ${nameList(nearMisses)}: capital letters matter)` : "";
    problems.push({
      level: "warn",
      code: "entry-missing-file",
      file: jsonRel,
      count: missing.length,
      names: missing,
      message: `${jsonRel} mentions ${nameList(missing)}, but ${one ? "that file is" : "those files are"} not in the folder${hint}; remove the ${one ? "entry" : "entries"} or put the ${one ? "photo" : "photos"} back.`,
    });
  }
  if (unknown.size > 0) {
    const names = [...unknown.keys()];
    problems.push({
      level: "warn",
      code: "json-unknown-key",
      file: jsonRel,
      message: `${jsonRel} uses ${nameList(names)}, which ${names.length === 1 ? "is not a setting" : "are not settings"} this site reads (it reads ${META_FIELDS.join(", ")}).`,
    });
  }
  return { state: "ok", entries };
}

/* --------------------------------------------------------------- media.json */

const ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

function normaliseImagePath(value) {
  if (typeof value !== "string" || !value.trim()) return null;
  let p = value.trim();
  if (p.startsWith("images/")) p = `/${p}`;
  return p.startsWith("/images/") ? p : null;
}

/**
 * src/content/media.json: the fixed pictures (slots) and the crops made from
 * them. Returns clean definitions; anything wrong becomes a problem line and
 * that slot or crop is left out, so the page renders nothing in that spot
 * instead of a broken image.
 */
function readMediaSettings(raw, jsonRel, problems) {
  const slots = new Map();
  const crops = new Map();
  if (raw === null) return { state: "none", slots, crops };
  const parsed = parseOwnerJson(raw);
  if (!parsed.ok) {
    problems.push({
      level: "error",
      code: "media-json-invalid",
      file: jsonRel,
      message: `${jsonRel} has a typo (${parsed.where}), so none of the fixed pictures it sets (such as the home hero) can be shown until it is fixed.`,
    });
    return { state: "invalid", slots, crops };
  }
  const data = parsed.data;
  if (data === null || typeof data !== "object" || Array.isArray(data)) {
    problems.push({
      level: "error",
      code: "media-json-invalid",
      file: jsonRel,
      message: `${jsonRel} must be one { } block with "slots" and "crops" inside, so none of the fixed pictures it sets can be shown until it is fixed.`,
    });
    return { state: "invalid", slots, crops };
  }
  const section = (name) => {
    const value = data[name];
    if (value === undefined) return [];
    if (value === null || typeof value !== "object" || Array.isArray(value)) {
      problems.push({
        level: "error",
        code: "media-json-invalid",
        file: jsonRel,
        message: `${jsonRel}: "${name}" must be a { } block, so nothing inside it can be used until it is fixed.`,
      });
      return [];
    }
    return Object.entries(value).filter(([id]) => !id.startsWith("_"));
  };
  const invalid = (kind, id, why) =>
    problems.push({
      level: "error",
      code: `${kind}-invalid`,
      file: jsonRel,
      key: id,
      message: `${jsonRel}: the ${kind} "${id}" ${why}, so that spot stays empty until it is fixed.`,
    });

  for (const [id, value] of section("slots")) {
    if (!ID_PATTERN.test(id)) {
      invalid("slot", id, "has a name with characters other than letters, numbers, dots and dashes");
      continue;
    }
    if (value === null || typeof value !== "object" || Array.isArray(value)) {
      invalid("slot", id, "must be a { } block of settings");
      continue;
    }
    const image = normaliseImagePath(value.image);
    if (!image) {
      invalid("slot", id, 'needs an "image" that starts with /images/');
      continue;
    }
    const slot = { id, image };
    if (typeof value.alt === "string" && value.alt.trim()) {
      const hits = findClaims(value.alt);
      if (hits.length > 0) {
        problems.push({
          level: "error",
          code: "claims",
          file: jsonRel,
          key: `${id} > alt`,
          message: `${jsonRel}: "alt" for the slot "${id}" contains a ${hits[0].kind} ("${hits[0].text}"); prices and response times must not be typed into photo text, so remove it and run this again.`,
        });
      } else {
        slot.alt = value.alt.trim();
      }
    }
    if (typeof value.position === "string" && value.position.trim()) slot.position = value.position.trim();
    const m = value.mobile;
    if (m !== undefined && m !== null) {
      if (typeof m !== "object" || Array.isArray(m)) {
        invalid("slot", id, 'has a "mobile" setting that is not a { } block');
        continue;
      }
      const mobile = {};
      const aspect = parseAspect(m.aspect ?? "4/5");
      if (Number.isNaN(aspect)) {
        invalid("slot", id, 'has a "mobile" shape that is not written like "4/5"');
        continue;
      }
      mobile.aspect = aspect;
      const focal = m.focal ?? [0.5, 0.5];
      if (!Array.isArray(focal) || focal.length !== 2 || !focal.every((v) => typeof v === "number" && v >= 0 && v <= 1)) {
        invalid("slot", id, 'has a "focal" point that is not two numbers between 0 and 1');
        continue;
      }
      mobile.focal = [focal[0], focal[1]];
      if (m.maxWidth !== undefined) {
        if (!Number.isInteger(m.maxWidth) || m.maxWidth < 1) {
          invalid("slot", id, 'has a "maxWidth" that is not a whole number of pixels');
          continue;
        }
        mobile.maxWidth = m.maxWidth;
      }
      if (typeof m.position === "string" && m.position.trim()) mobile.position = m.position.trim();
      slot.mobile = mobile;
    }
    slots.set(id, slot);
  }

  for (const [id, value] of section("crops")) {
    if (!ID_PATTERN.test(id)) {
      invalid("crop", id, "has a name with characters other than letters, numbers, dots and dashes");
      continue;
    }
    if (value === null || typeof value !== "object" || Array.isArray(value)) {
      invalid("crop", id, "must be a { } block of settings");
      continue;
    }
    const image = normaliseImagePath(value.image);
    if (!image) {
      invalid("crop", id, 'needs an "image" that starts with /images/');
      continue;
    }
    const box = value.box;
    const numbers = box && ["left", "top", "width", "height"].map((k) => box[k]);
    if (!numbers || !numbers.every((v) => Number.isInteger(v) && v >= 0)) {
      invalid("crop", id, 'needs a "box" with whole numbers for left, top, width and height');
      continue;
    }
    crops.set(id, { id, image, box: { left: box.left, top: box.top, width: box.width, height: box.height } });
  }
  return { state: "ok", slots, crops };
}

/* ------------------------------------------------------------------ analyse */

const inCollectionRoot = (folder) => COLLECTION_ROOTS.some((r) => folder === r || folder.startsWith(`${r}/`));
/** Covers are counted per project (projects/<slug>, all its phases) and per folder elsewhere. */
const coverGroup = (folder) => {
  const parts = folder.split("/");
  return parts[0] === "projects" && parts.length >= 2 ? parts.slice(0, 2).join("/") : folder;
};

/**
 * Read the project and work out everything, writing nothing: every picture
 * with its measurements and settings, the ordered list of each folder, the
 * resolved slots, the crops to render and every problem found on the way.
 * scripts/check-images.mjs builds its report from the same result.
 */
export async function analyse({ root = REPO_ROOT, useCache = true } = {}) {
  const started = performance.now();
  const P = projectPaths(root);
  const problems = [];
  const counters = { measured: 0, cached: 0 };
  const scan = await scanImages(P.images);

  const tool = sharpVersion();
  const cache = useCache ? await loadCache(P.cache, tool) : { v: CACHE_VERSION, tool, files: {}, derived: {} };
  const measurable = [...scan.files, ...scan.held].map((f) => ({ ...f, key: f.rel }));
  const measured = await measureAll(measurable, cache, counters);
  cache.files = measured;

  // Files that claim to be pictures but are not something a browser can show.
  const records = new Map();
  const unsupported = scan.unsupported.map((u) => ({ rel: u.rel, what: UNSUPPORTED_EXT.get(u.ext) }));
  const heldRecords = [];
  for (const item of [...scan.files, ...scan.held]) {
    const cached = measured[item.rel];
    if (!cached) continue;
    const m = cached.m;
    const isHeld = scan.held.includes(item);
    if (m.bad === "heic" || m.bad === "tiff") {
      unsupported.push({ rel: item.rel, what: m.bad === "heic" ? "really an iPhone HEIC photo with a different ending" : "really a TIFF file with a different ending" });
      continue;
    }
    if (m.bad) {
      if (!isHeld) {
        problems.push({
          level: "warn",
          code: "unreadable-file",
          file: `public/images/${item.rel}`,
          message: `public/images/${item.rel} cannot be opened as a picture, so it is left off the site; export or save it again and replace the file.`,
        });
      }
      continue;
    }
    const record = {
      path: publicPath(item.rel),
      rel: item.rel,
      abs: item.abs,
      folder: item.folder,
      file: item.file,
      kind: item.kind,
      format: m.f,
      width: m.w,
      height: m.h,
      bytes: cached.s,
      sha256: cached.sha.slice(0, 16),
      shaFull: cached.sha,
      color: m.c,
      alpha: Boolean(m.a),
      exif: Boolean(m.x),
      gps: Boolean(m.g),
      settings: {},
    };
    if (isHeld) heldRecords.push(record);
    else records.set(record.path, record);
  }

  // images.json, folder by folder.
  const byFolder = new Map(scan.dirs.map((d) => [d, []]));
  for (const record of records.values()) byFolder.get(record.folder)?.push(record);
  const folderState = new Map();
  for (const folder of scan.dirs) {
    const jsonAbs = scan.metaFiles.get(folder);
    if (!jsonAbs) {
      folderState.set(folder, "none");
      continue;
    }
    const jsonRel = rel(root, jsonAbs);
    const raw = (await readIfExists(jsonAbs, "utf8")) ?? "";
    // Entries may name any picture that is really in the folder, readable or not.
    const names = scan.files.filter((f) => f.folder === folder).map((f) => f.file);
    const { state, entries } = readFolderSettings(raw, jsonRel, names, problems);
    folderState.set(folder, state);
    for (const record of byFolder.get(folder) ?? []) {
      const entry = entries.get(record.file);
      if (entry) record.settings = entry;
    }
  }

  // Fixed pictures and crops.
  const mediaRaw = await readIfExists(P.mediaJson, "utf8");
  const mediaRel = rel(root, P.mediaJson);
  const media = readMediaSettings(mediaRaw, mediaRel, problems);
  const slots = {};
  const derived = [];
  const derivedIds = new Set();
  const addDerived = (spec) => {
    if (derivedIds.has(spec.id)) {
      problems.push({
        level: "error",
        code: "crop-invalid",
        file: mediaRel,
        key: spec.id,
        message: `${mediaRel}: two settings would both make a picture named "${spec.id}", so the second one is skipped; rename one of them.`,
      });
      return false;
    }
    derivedIds.add(spec.id);
    derived.push(spec);
    return true;
  };

  for (const slot of media.slots.values()) {
    const source = records.get(slot.image);
    if (!source) {
      problems.push({
        level: "error",
        code: "slot-image-missing",
        file: mediaRel,
        key: slot.id,
        message: `${mediaRel}: the picture for "${slot.id}" (${slot.image}) is not in public/images, so that spot stays empty; put the file back or point "image" at another one.`,
      });
      continue;
    }
    const resolved = { image: slot.image };
    if (slot.alt) resolved.alt = slot.alt;
    if (slot.position) resolved.position = slot.position;

    // The owner's own portrait cut beside the picture ("<name>-mobile.<ext>")
    // wins over a generated crop. Same ending first, then any other picture type.
    const siblings = (byFolder.get(source.folder) ?? [])
      .filter((r) => r.kind === "raster" && r !== source && !r.settings.hidden && stem(r.file) === `${stem(source.file)}-mobile`)
      .sort((a, b) => byCodePoint(a.file, b.file));
    const sibling = siblings.find((r) => path.extname(r.file) === path.extname(source.file)) ?? siblings[0];
    if (sibling) {
      sibling.mobileOf = source.path;
      resolved.mobile = sibling.path;
    } else if (slot.mobile && source.kind === "raster" && source.format !== "gif") {
      const box = mobileCropBox({ width: source.width, height: source.height, aspect: slot.mobile.aspect, focal: slot.mobile.focal });
      const full = box.width === source.width && box.height === source.height;
      const shrinks = slot.mobile.maxWidth !== undefined && slot.mobile.maxWidth < box.width;
      if (!full || shrinks) {
        const id = `${slot.id}.mobile`;
        if (addDerived({ id, source, box, maxWidth: shrinks ? slot.mobile.maxWidth : undefined })) resolved.mobile = `derived:${id}`;
      }
    }
    if (resolved.mobile && slot.mobile?.position) resolved.mobilePosition = slot.mobile.position;
    slots[slot.id] = resolved;
    if (source.settings.hidden) {
      problems.push({
        level: "warn",
        code: "slot-hidden",
        file: mediaRel,
        key: slot.id,
        message: `${mediaRel}: the picture for "${slot.id}" (${slot.image}) is marked hidden in its folder's images.json, so that spot stays empty until "hidden" is removed.`,
      });
    }
  }

  for (const crop of media.crops.values()) {
    const source = records.get(crop.image);
    if (!source) {
      problems.push({
        level: "error",
        code: "crop-image-missing",
        file: mediaRel,
        key: crop.id,
        message: `${mediaRel}: the picture for the crop "${crop.id}" (${crop.image}) is not in public/images, so that spot stays empty; put the file back or point "image" at another one.`,
      });
      continue;
    }
    if (source.kind !== "raster" || source.format === "gif") {
      problems.push({
        level: "error",
        code: "crop-invalid",
        file: mediaRel,
        key: crop.id,
        message: `${mediaRel}: the crop "${crop.id}" points at a ${source.kind === "vector" ? "vector (SVG)" : "GIF"} file, which cannot be cropped, so that spot stays empty; use a PNG, JPG or WebP picture.`,
      });
      continue;
    }
    if (crop.box.width === 0 || crop.box.height === 0) {
      problems.push({
        level: "note",
        code: "crop-empty",
        file: mediaRel,
        key: crop.id,
        message: `${mediaRel}: the crop "${crop.id}" has no size yet (width and height are 0), so nothing is made for it.`,
      });
      continue;
    }
    const left = clamp(crop.box.left, 0, source.width - 1);
    const top = clamp(crop.box.top, 0, source.height - 1);
    const box = { left, top, width: clamp(crop.box.width, 1, source.width - left), height: clamp(crop.box.height, 1, source.height - top) };
    if (box.left !== crop.box.left || box.top !== crop.box.top || box.width !== crop.box.width || box.height !== crop.box.height) {
      problems.push({
        level: "warn",
        code: "crop-clamped",
        file: mediaRel,
        key: crop.id,
        message: `${mediaRel}: the box for the crop "${crop.id}" reaches outside its ${source.width} x ${source.height} picture, so it was trimmed to fit; adjust the numbers when convenient.`,
      });
    }
    addDerived({ id: crop.id, source, box });
  }

  // Ordered lists.
  const visible = (r) => !r.settings.hidden && !r.mobileOf;
  const ordered = (list, compare) => {
    const withOrder = list.filter((r) => typeof r.settings.order === "number").sort((a, b) => a.settings.order - b.settings.order || compare(a, b));
    const rest = list.filter((r) => typeof r.settings.order !== "number").sort(compare);
    return [...withOrder, ...rest].map((r) => r.path);
  };
  const folders = [...scan.dirs].sort(compareFolders);
  const collections = {};
  const trees = {};
  for (const folder of folders) {
    const direct = (byFolder.get(folder) ?? []).filter(visible);
    const hasFiles = (byFolder.get(folder) ?? []).length > 0 || scan.metaFiles.has(folder);
    const hasChildDirs = folders.some((f) => f !== folder && (folder === "" || f.startsWith(`${folder}/`)));
    if (hasFiles || !hasChildDirs) collections[folder] = ordered(direct, (a, b) => compareFileNames(a.file, b.file));
    if (hasChildDirs && folder !== "") {
      const below = [...records.values()].filter((r) => visible(r) && (r.folder === folder || r.folder.startsWith(`${folder}/`)));
      trees[folder] = ordered(below, (a, b) => comparePaths(a.rel, b.rel));
    }
  }

  // More than one cover in a project.
  const covers = new Map();
  for (const record of records.values()) {
    if (!record.settings.cover || record.settings.hidden) continue;
    const group = coverGroup(record.folder);
    if (!covers.has(group)) covers.set(group, []);
    covers.get(group).push(record);
  }
  for (const [group, list] of [...covers].sort((a, b) => compareFolders(a[0], b[0]))) {
    if (list.length < 2) continue;
    const names = list.sort((a, b) => comparePaths(a.rel, b.rel)).map((r) => r.rel.slice(group.length + 1) || r.file);
    problems.push({
      level: "warn",
      code: "multiple-covers",
      file: `public/images/${group}`,
      message: `public/images/${group} has ${list.length} photos marked "cover" (${nameList(names)}); keep "cover" on one of them and remove it from the ${list.length === 2 ? "other" : "others"}.`,
    });
  }

  return {
    root,
    paths: P,
    tool,
    cache,
    scan,
    records,
    heldRecords,
    unsupported,
    folders,
    folderState,
    byFolder,
    collections,
    trees,
    slots,
    derived,
    media,
    problems,
    counters,
    ms: performance.now() - started,
    inCollection: (folder) => inCollectionRoot(folder) || folderState.get(folder) === "ok" || folderState.get(folder) === "invalid",
  };
}

/* ----------------------------------------------------------------- generate */

function encodeFor(pipeline, ext, sourceMeta) {
  switch (ext) {
    case "jpg":
    case "jpeg":
      return pipeline.jpeg({
        quality: 90,
        chromaSubsampling: sourceMeta.chromaSubsampling === "4:4:4" ? "4:4:4" : "4:2:0",
        progressive: Boolean(sourceMeta.isProgressive),
      });
    case "png":
      return pipeline.png({ compressionLevel: 9 });
    case "webp":
      return pipeline.webp({ quality: 90 });
    case "avif":
      return pipeline.avif({ quality: 80 });
    default:
      throw new Error(`cannot write .${ext}`);
  }
}

/**
 * A crop and nothing else: upright pixels, the box, an optional shrink to
 * maxWidth (never an enlargement). No colour change, no sharpening; the
 * colour profile of the source, when it has one, travels with the crop.
 */
async function renderDerived(spec) {
  const sharp = await loadSharp();
  const sourceMeta = await sharp(spec.source.abs, { failOn: "none" }).metadata();
  // Two steps so the box is always measured on the upright picture, whatever
  // rotation flag the file carries.
  const upright = await sharp(spec.source.abs, { failOn: "none" }).rotate().keepIccProfile().png({ compressionLevel: 0 }).toBuffer();
  let pipeline = sharp(upright).extract(spec.box);
  if (spec.maxWidth) pipeline = pipeline.resize({ width: spec.maxWidth, withoutEnlargement: true });
  if (sourceMeta.icc) pipeline = pipeline.keepIccProfile();
  const data = await encodeFor(pipeline, spec.ext, sourceMeta).toBuffer();
  const meta = await sharp(data).metadata();
  const thumb = await sharp(data).resize(48, 48, { fit: "inside" }).toColourspace("srgb").raw().toBuffer({ resolveWithObject: true });
  const { color, alpha } = dominantColour(thumb.data, thumb.info.channels);
  return { data, width: meta.width, height: meta.height, color, alpha };
}

const FIELD_ORDER = ["alt", "caption", "title", "category", "id", "order", "position", "hidden", "cover", "featured"];

function metaEntry(record) {
  const out = {
    path: record.path,
    folder: record.folder,
    file: record.file,
    width: record.width,
    height: record.height,
    bytes: record.bytes,
    sha256: record.sha256,
  };
  if (record.color) out.color = record.color;
  if (record.alpha) out.alpha = true;
  if (record.kind === "vector") out.vector = true;
  for (const field of FIELD_ORDER) {
    if (record.settings[field] !== undefined) out[field] = record.settings[field];
  }
  if (record.mobileOf) out.mobileOf = record.mobileOf;
  return out;
}

/**
 * Produce (or, with write: false, only compare) everything in src/generated.
 * Returns the list of files that changed or, in check mode, that are stale.
 */
export async function generate(analysis, { write = true } = {}) {
  const { paths: P, records, derived, cache } = analysis;
  const changed = [];
  const note = (file) => changed.push(rel(analysis.root, file));
  const derivedDir = path.join(P.generated, "derived");
  const stagedDir = path.join(P.generated, "staged");

  // Which pictures are imported, and from where.
  const imports = [];
  const expectedStaged = new Set();
  const published = [...records.values()].filter((r) => r.kind === "raster" && !r.settings.hidden).sort((a, b) => byCodePoint(a.path, b.path));
  for (const record of published) {
    if (!needsStaging(record.rel, record.format)) {
      imports.push({ key: record.path, from: `../../public/images/${record.rel}` });
      continue;
    }
    let tagLength = 6;
    let name = stagedName(record.rel, record.format, tagLength);
    while (expectedStaged.has(name) && tagLength < 64) {
      tagLength += 4;
      name = stagedName(record.rel, record.format, tagLength);
    }
    expectedStaged.add(name);
    record.staged = name;
    const target = path.join(stagedDir, name);
    let current = null;
    try {
      const info = await stat(target);
      if (info.size === record.bytes) current = (await sha256File(target)) === record.shaFull;
    } catch {
      current = null;
    }
    if (!current) {
      note(target);
      if (write) {
        // Copy beside the target, then swap it in, so a dev server never sees half a file.
        await mkdir(stagedDir, { recursive: true });
        const tmp = `${target}.tmp-${process.pid}`;
        await rm(tmp, { force: true });
        await copyFile(record.abs, tmp, FS.COPYFILE_FICLONE);
        await rename(tmp, target);
      }
    }
    imports.push({ key: record.path, from: `./staged/${name}` });
  }

  // Crops.
  const derivedMeta = {};
  const expectedDerived = new Set();
  for (const spec of [...derived].sort((a, b) => byCodePoint(a.id, b.id))) {
    spec.ext = CANONICAL_EXT[spec.source.format][0];
    const name = `${spec.id}.${spec.ext}`;
    expectedDerived.add(name);
    const target = path.join(derivedDir, name);
    const key = JSON.stringify([GENERATOR_VERSION, analysis.tool, spec.source.shaFull, spec.box, spec.maxWidth ?? null, spec.ext]);
    let entry = cache.derived[spec.id];
    let onDisk = null;
    try {
      onDisk = await stat(target);
    } catch {
      onDisk = null;
    }
    const upToDate = entry && entry.key === key && onDisk && onDisk.size === entry.bytes && (await sha256File(target)) === entry.sha;
    if (!upToDate) {
      const out = await renderDerived(spec);
      const sha = createHash("sha256").update(out.data).digest("hex");
      const same = onDisk && onDisk.size === out.data.length && (await sha256File(target)) === sha;
      if (!same) {
        note(target);
        if (write) await writeIfChanged(target, out.data);
      }
      entry = { key, sha, bytes: out.data.length, w: out.width, h: out.height, c: out.color, a: out.alpha };
      cache.derived[spec.id] = entry;
    }
    const metaOut = {
      path: `derived:${spec.id}`,
      folder: "",
      file: name,
      width: entry.w,
      height: entry.h,
      bytes: entry.bytes,
      sha256: entry.sha.slice(0, 16),
      color: entry.c,
    };
    if (entry.a) metaOut.alpha = true;
    metaOut.derived = true;
    metaOut.source = spec.source.path;
    metaOut.box = spec.box;
    derivedMeta[`derived:${spec.id}`] = metaOut;
    imports.push({ key: `derived:${spec.id}`, from: `./derived/${name}` });
  }
  for (const id of Object.keys(cache.derived)) {
    if (!derived.some((d) => d.id === id)) delete cache.derived[id];
  }

  // Leftovers from pictures or settings that no longer exist.
  for (const [dir, expected] of [
    [stagedDir, expectedStaged],
    [derivedDir, expectedDerived],
  ]) {
    let names = [];
    try {
      names = await readdir(dir);
    } catch {
      names = [];
    }
    for (const name of names) {
      if (expected.has(name)) continue;
      if (name.includes(".tmp-")) {
        // Another run may be writing this right now; only sweep it up once it is clearly abandoned.
        const age = await stat(path.join(dir, name)).then((s) => Date.now() - s.mtimeMs, () => 0);
        if (age < 60_000) continue;
      }
      note(path.join(dir, name));
      if (write) await rm(path.join(dir, name), { force: true, recursive: true });
    }
  }

  // images.ts
  const lines = [
    ...HEADER,
    "//",
    "// One static import per published picture, so each is served from a URL that",
    "// contains a hash of its contents. Server-only: read it through",
    '// src/lib/media.ts, never from a "use client" file.',
    'import type { StaticImageData } from "next/image";',
    ...imports.map((imp, n) => `import i${n} from ${JSON.stringify(imp.from)};`),
    "",
    "export const IMAGES: Record<string, StaticImageData> = {",
    ...imports.map((imp, n) => `  ${JSON.stringify(imp.key)}: i${n},`),
    "};",
    "",
  ];
  const imagesTs = lines.join("\n");

  // images-meta.json
  const images = {};
  for (const record of [...records.values()].sort((a, b) => byCodePoint(a.path, b.path))) images[record.path] = metaEntry(record);
  for (const key of Object.keys(derivedMeta).sort(byCodePoint)) images[key] = derivedMeta[key];
  const slots = {};
  for (const id of Object.keys(analysis.slots).sort(byCodePoint)) slots[id] = analysis.slots[id];
  const meta = {
    version: GENERATOR_VERSION,
    images,
    folders: analysis.folders.filter((f) => Object.hasOwn(analysis.collections, f)),
    collections: analysis.collections,
    trees: analysis.trees,
    slots,
  };
  // One picture, one folder, one slot per line: small, and easy to search or diff.
  const block = (value) => {
    const rows = Object.entries(value).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`);
    return rows.length > 0 ? `{\n${rows.join(",\n")}\n  }` : "{}";
  };
  const metaJson = [
    "{",
    `  "version": ${JSON.stringify(meta.version)},`,
    `  "images": ${block(meta.images)},`,
    `  "folders": ${JSON.stringify(meta.folders)},`,
    `  "collections": ${block(meta.collections)},`,
    `  "trees": ${block(meta.trees)},`,
    `  "slots": ${block(meta.slots)}`,
    "}",
    "",
  ].join("\n");

  // Lets `tsc` understand the image imports on a fresh clone, before Next has
  // written next-env.d.ts.
  const typesDts = [...HEADER, '/// <reference types="next/image-types/global" />', ""].join("\n");

  for (const [name, content] of [
    ["images.ts", imagesTs],
    ["images-meta.json", metaJson],
    ["image-types.d.ts", typesDts],
  ]) {
    const file = path.join(P.generated, name);
    if (write) {
      if (await writeIfChanged(file, content)) note(file);
    } else if ((await readIfExists(file, "utf8")) !== content) {
      note(file);
    }
  }

  return { changed, imported: imports.length, staged: expectedStaged.size, derived: expectedDerived.size };
}

/* ---------------------------------------------------------------------- cli */

export function parseArgs(argv) {
  const flags = new Set();
  const values = {};
  const rest = [];
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--root") {
      values.root = argv[i + 1];
      i += 1;
    } else if (arg.startsWith("--root=")) {
      values.root = arg.slice("--root=".length);
    } else if (arg.startsWith("--")) {
      flags.add(arg.slice(2));
    } else {
      rest.push(arg);
    }
  }
  const root = path.resolve(values.root ?? process.env.CS_IMAGES_ROOT ?? REPO_ROOT);
  return { flags, root, rest };
}

/** Problem codes this step prints. The per-photo ones (alt text, size, EXIF) belong to check-images. */
const PRINTED = new Set([
  "json-invalid",
  "json-shape",
  "json-unknown-key",
  "entry-missing-file",
  "claims",
  "unreadable-file",
  "media-json-invalid",
  "slot-invalid",
  "crop-invalid",
  "slot-image-missing",
  "crop-image-missing",
  "slot-hidden",
  "crop-clamped",
  "crop-empty",
  "multiple-covers",
]);

/**
 * The whole step. `exitCode` is 1 when photo text contains a price or a
 * response-time figure, or (with check) when src/generated is stale.
 */
export async function run({ root = REPO_ROOT, check = false, quiet = false, useCache = true, log = console.log, warn = console.error } = {}) {
  const started = performance.now();
  const analysis = await analyse({ root, useCache });
  const result = await generate(analysis, { write: !check });
  if (useCache) await saveCache(analysis.paths.cache, analysis.cache);

  const printed = analysis.problems.filter((p) => PRINTED.has(p.code) && !(p.level === "note" && quiet));
  for (const problem of printed) warn(`image manifest: ${problem.message}`);

  const failed = analysis.problems.some((p) => p.code === "claims");
  const stale = check && result.changed.length > 0;
  if (stale) {
    warn(`image manifest: src/generated is out of date (${nameList(result.changed, 3)}); run \`npm run images:manifest\`.`);
  }
  const outcome = {
    exitCode: failed || stale ? 1 : 0,
    changed: result.changed,
    measured: analysis.counters.measured,
    cached: analysis.counters.cached,
    problems: printed.map((p) => ({ level: p.level, code: p.code, file: p.file, key: p.key, message: p.message })),
    seconds: 0,
  };
  if (!quiet) {
    const vectors = [...analysis.records.values()].filter((r) => r.kind === "vector").length;
    const parts = [
      `${plural(analysis.records.size - vectors, "picture")} and ${plural(vectors, "vector file")} in ${plural(Object.keys(analysis.collections).length, "folder")}`,
      `${result.imported} imported (${result.staged} through a web-safe copy, ${result.derived} cropped)`,
      `${analysis.counters.measured} measured, ${analysis.counters.cached} from cache`,
      check ? (stale ? "STALE" : "up to date") : result.changed.length > 0 ? `${plural(result.changed.length, "file")} written` : "nothing changed",
      `${((performance.now() - started) / 1000).toFixed(2)}s`,
    ];
    log(`image manifest: ${parts.join("; ")}`);
  }
  outcome.seconds = Number(((performance.now() - started) / 1000).toFixed(3));
  return outcome;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isMain) {
  const { flags, root } = parseArgs(process.argv.slice(2));
  // --json: one machine-readable line on stdout (scripts/dev.mjs reads it); problems still go to stderr.
  const json = flags.has("json");
  run({ root, check: flags.has("check"), quiet: json || flags.has("quiet"), useCache: !flags.has("no-cache") })
    .then((outcome) => {
      if (json) console.log(JSON.stringify(outcome));
      process.exitCode = outcome.exitCode;
    })
    .catch((err) => {
      console.error(`image manifest: stopped by an unexpected error: ${err?.stack ?? err}`);
      process.exitCode = 1;
    });
}
